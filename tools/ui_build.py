"""Bundle local UI factories; no runtime HTTP, filesystem imports or loadstring."""
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def ui_sources() -> dict[str, str]:
    directory = ROOT / 'ui'
    sources = {
        path.relative_to(directory).with_suffix('').as_posix(): path.read_text(encoding='utf-8-sig')
        for path in sorted(directory.rglob('*.lua'))
    }
    if 'init' not in sources:
        raise ValueError('Missing ui/init.lua')
    dependencies = {}
    for name, source in sources.items():
        if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*(/[A-Za-z_][A-Za-z_0-9]*)*', name):
            raise ValueError(f'Invalid UI module name: {name}')
        dependencies[name] = re.findall(r'\bimport\("([^"]+)"\)', source)
        for dependency in dependencies[name]:
            if dependency not in sources:
                raise ValueError(f'{name}: missing UI dependency {dependency}')
    visited, visiting = set(), set()

    def visit(name):
        if name in visiting:
            raise ValueError(f'Circular UI dependency: {name}')
        if name in visited:
            return
        visiting.add(name)
        for dependency in dependencies[name]:
            visit(dependency)
        visiting.remove(name)
        visited.add(name)

    for name in sources:
        visit(name)
    return sources


def registry(sources: dict[str, str]) -> str:
    lines = ['local uiFactories = {}']
    for name, source in sources.items():
        lines.extend([f'-- Source: ui/{name}.lua', f'uiFactories["{name}"] = function(...)', source, 'end'])
    lines.append('''local uiCache, uiLoading = {}, {}
local function importUI(name)
    if uiCache[name] ~= nil then return uiCache[name] end
    assert(not uiLoading[name], "Circular UI dependency: " .. name)
    local factory = assert(uiFactories[name], "Missing UI component: " .. name)
    uiLoading[name] = true
    local ok, result = pcall(factory, importUI)
    uiLoading[name] = nil
    if not ok then error(result, 0) end
    assert(result ~= nil, "UI component returned nil: " .. name)
    uiCache[name] = result
    return result
end''')
    return '\n'.join(lines) + '\n'


def build_ui() -> str:
    sources = ui_sources()
    digest = hashlib.sha256()
    for name, source in sources.items():
        digest.update(name.encode() + b'\0' + source.encode())
    return (
        '-- Generated by tools/build.py from ui/. Do not edit this file directly.\n'
        f'-- UI source SHA-256: {digest.hexdigest()}\n'
        + registry(sources)
        + 'return importUI("init")(...)\n'
    )


def check_ui() -> None:
    output = ROOT / 'DiqUILib.lua'
    if not output.exists() or output.read_text(encoding='utf-8-sig') != build_ui():
        raise ValueError('DiqUILib.lua is stale. Run python tools/build.py --ui-only')
