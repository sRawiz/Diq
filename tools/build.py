"""Build a self-contained executor entry point without fetching/executing code."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build() -> str:
    manifest = json.loads((ROOT / 'module-manifest.json').read_text(encoding='utf-8'))
    names = [*manifest['modules'], manifest['entry']]
    if len(set(names)) != len(names):
        raise ValueError('Duplicate module in manifest')
    for name in names:
        if not name.isidentifier():
            raise ValueError('Module names must be identifiers')
    sources = {name: (ROOT / f'{name}.lua').read_text(encoding='utf-8-sig') for name in names}
    digest = hashlib.sha256()
    for name, source in sources.items():
        digest.update(name.encode())
        digest.update(b'\0')
        digest.update(source.encode())
    lines = [
        '-- Generated by tools/build.py. Edit source files, then rebuild.',
        f'-- Source SHA-256: {digest.hexdigest()}',
        'local bundled = {}',
    ]
    for name in manifest['modules']:
        lines.extend([f'bundled.{name} = function(...)', sources[name], 'end'])
    lines.extend([
        'local function entry(...)', sources[manifest['entry']], 'end',
        'local supplied = ...',
        'local options = type(supplied) == "table" and table.clone(supplied) or {}',
        'options.Factories = bundled',
        'return entry(options)',
    ])
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'dist/Diq.lua')
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build(), encoding='utf-8', newline='\n')
    print(f'Built {args.output.resolve()}')
